'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const files=['data-base.js',...Array.from({length:12},(_,i)=>`p${i+1}.js`),'data-extra.js','core-a.js','core-b.js','scene-helpers.js','scene-p1-4.js','scene-p5-8.js','scene-p9-12.js','scene-dispatch.js','accuracy-fixes.js','accuracy-p2-p6.js','accuracy-p7-p12.js','accuracy-final.js','accuracy-browser-fixes.js','aqa-setup-alignment.js','aqa-setup-visual-fixes.js','p2-visual-accuracy.js'];
const ctx={console,Math,localStorage:{getItem:()=>null,setItem(){}},document:{querySelector:()=>null,querySelectorAll:()=>[],readyState:'loading'},addEventListener(){},setTimeout(){},runExperiment(){},resetExperiment(){},renderP1Scene(){},renderP2Scene(){},renderP3Scene(){},renderP4Scene(){},renderP5Scene(){},renderP6Scene(){},renderP7Scene(){},renderP8Scene(){},renderP9Scene(){},renderP10Scene(){},renderP11Scene(){},renderP12Scene(){}};
ctx.window=ctx;
vm.createContext(ctx);
for(const file of files)vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx,{filename:file});
const run=code=>vm.runInContext(code,ctx);

run('current=practicals[0];currentMode=0;state.vals_1_0=[0.8,4.9,1.5];simT=0.07;running=true;');
const f1=run('theoretical().read.Resonance');
assert.equal(f1,'35.7 Hz');
const resonant=run('theoretical().read.Amplitude');
run('state.p1_drive_0=55');
const detuned=run('theoretical().read.Amplitude');
assert.ok(parseInt(resonant)>parseInt(detuned),'P1 antinode amplitude must fall off resonance');
assert.match(run('renderP1Scene()'),/OFF RESONANCE/);
run('state.vals_1_0=[1.2,4.9,1.5]');
assert.equal(run('theoretical().read.Resonance'),'23.8 Hz','P1 changing length changes resonance');

run('current=practicals[1];currentMode=0;state.vals_2_0=[632.8,1.5,0.4];simT=0;running=false;');
const young=run('renderP2Scene()');
const screenOf=html=>html.match(/<g data-part="Screen"[\s\S]*?<\/g>/)?.[0]||'';
const screen=screenOf(young);
assert.match(screen,/data-part="Five-fringe measurement"/,'P2 measurement should move with screen');
assert.ok(run('p2DoubleSlitIntensity(0,632.8,1.5,0.4)')>.99);
assert.ok(run('p2DoubleSlitIntensity(1.1865,632.8,1.5,0.4)')<.01);
run('simT=4;running=true;');
const active=run('renderP2Scene()');
assert.equal(screenOf(active),screen,'P2 steady interference pattern must not pulse with time');
assert.notEqual(active,young,'P2 propagation cue should animate');
run('currentMode=1;state.vals_2_1=[632.8,1.5,0.002];state.p2_grating_order=1;');
const grating=run('theoretical()');
assert.ok(Math.abs(grating.y-632.8e-9/0.002e-3)<1e-9,'P2 grating order angle follows nλ=d sinθ');

run('current=practicals[2];currentMode=0;state.vals_3_0=[0.5,1,2];simT=0;running=false;');
const ready=run('renderP3Scene()');
assert.match(ready,/data-part="Impact pad"/);
assert.doesNotMatch(ready,/data-part="Light gate"/);
assert.match(ready,/0\.0000 s/);
run('simT=0.16;running=true;');
const first=run('renderP3Scene()');
const ballY=html=>+(html.match(/data-part="Ball bearing"[^>]*><circle[^>]*cy="([\d.]+)"/)||[])[1];
const initialY=ballY(first);
assert.ok(initialY>104&&initialY<330,'P3 ball should be mid-fall');
run('state.vals_3_0=[0.5,5,8]');
const changed=run('renderP3Scene()');
assert.equal(ballY(changed),initialY,'P3 timing error must not alter the ball trajectory');
assert.notEqual(run('theoretical([0.5,5,8]).read.Time'),run('theoretical([0.5,1,2]).read.Time'),'P3 timing controls affect timer reading');
run('currentMode=1;state.vals_3_1=[0.5,1,2];simT=0;running=false;');
assert.match(run('renderP3Scene()'),/data-part="Light gate"/);
run('simT=0.5;running=true;');
const landed=run('renderP3Scene()');
assert.equal(ballY(landed),330);
assert.match(landed,/CAPTURED/);
assert.equal(run('running'),false,'P3 animation stops after capture');
console.log('Practicals 1–3 physics and animation regressions passed.');

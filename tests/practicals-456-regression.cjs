'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const scripts=['data-base.js',...Array.from({length:12},(_,i)=>`p${i+1}.js`),'data-extra.js','core-a.js','core-b.js','scene-helpers.js','scene-p1-4.js','scene-p5-8.js','scene-p9-12.js','scene-dispatch.js','accuracy-fixes.js','accuracy-p2-p6.js','accuracy-p7-p12.js','accuracy-final.js','accuracy-browser-fixes.js','aqa-setup-alignment.js','aqa-setup-visual-fixes.js','p2-visual-accuracy.js','p4-p6-run-accuracy.js'];
const ctx={console,Math,localStorage:{getItem:()=>null,setItem(){}},document:{querySelector:()=>null,querySelectorAll:()=>[],readyState:'loading',addEventListener(){}},addEventListener(){},setTimeout(){},clearTimeout(){},renderCoach(){},renderScene(){},beep(){},runExperiment(){},resetExperiment(){},renderP1Scene(){},renderP2Scene(){},renderP3Scene(){},renderP4Scene(){},renderP5Scene(){},renderP6Scene(){},renderP7Scene(){},renderP8Scene(){},renderP9Scene(){},renderP10Scene(){},renderP11Scene(){},renderP12Scene(){}};
ctx.window=ctx;vm.createContext(ctx);
for(const file of scripts)vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx,{filename:file});
const run=code=>vm.runInContext(code,ctx);
run('renderCoach=()=>{};renderScene=()=>{};beep=()=>{};');
const wireY=svg=>+(svg.match(/data-part="Test wire"><line[^>]+y2="([\d.]+)"/)||[])[1];
const meter=(svg,name)=>+(svg.match(new RegExp(`data-part="${name}"[\\s\\S]*?<text[^>]*>([\\d.]+)<\\/text>`))||[])[1];

run('current=practicals[3];currentMode=0;state.vals_4_0=[20,1.5,.4];simT=0;running=true;');
const loadStart=wireY(run('renderP4Scene()'));
run('simT=.8');
const loadEnd=wireY(run('renderP4Scene()'));
assert.ok(loadEnd>loadStart,'P4 loading extends test wire');
run('currentMode=1;state.vals_4_1=[10,1.5,.4];simT=0;running=true;');
const unloadStart=wireY(run('renderP4Scene()'));
run('simT=.8');
const unloadEnd=wireY(run('renderP4Scene()'));
assert.ok(unloadEnd<unloadStart,'P4 unloading retracts test wire');
run('running=false;currentMode=0;state.vals_4_0=[20,2.5,.4]');
assert.ok(wireY(run('renderP4Scene()'))>338,'P4 high extension must not clip at old 18 px limit');

run('current=practicals[4];currentMode=0;state.vals_5_0=[.6,.15,.45];simT=0;running=false;');
const open=run('renderP5Scene()');
assert.match(open,/READY · SUPPLY OFF/);
assert.equal(meter(open,'Ammeter'),0);
assert.equal(+(open.match(/data-conducting-section[^>]*x2="([\d.]+)"/)||[])[1],517,'P5 highlighted section stops at selected contact');
run('simT=4;runExperiment()');
assert.equal(run('simT'),0,'P5 new run restarts the sequence');
run('simT=.5');
const lit=run('renderP5Scene()');
assert.ok(meter(lit,'Ammeter')>.07);
assert.match(lit,/data-conducting-section[^>]*stroke="#d3eca6"/);
run('simT=2');
const held=run('renderP5Scene()');
assert.equal(run('running'),false,'P5 opens after a brief reading');
assert.match(held,/HOLD READING · SUPPLY OFF/);
run('currentMode=1;state.vals_5_1=[.6,.15,.45];');
assert.equal(run('theoretical().x'),1/(.45*.45),'P5 diameter mode graphs R against 1/d²');
assert.equal(run('theoretical().read.Current'),'0.000 A','P5 held result does not leak into a different mode');

run('current=practicals[5];currentMode=0;state.vals_6_0=[8,1.5,.6];simT=0;running=false;');
const cellOpen=run('renderP6Scene()');
assert.equal(meter(cellOpen,'Ammeter'),0);
assert.equal(meter(cellOpen,'Voltmeter'),1.5);
run('simT=8;runExperiment()');
assert.equal(run('simT'),0,'P6 each paired reading starts at the switch closure');
run('simT=.7');
const cellClosed=run('renderP6Scene()');
assert.ok(Math.abs(meter(cellClosed,'Ammeter')-1.5/8.6)<.002);
assert.ok(Math.abs(meter(cellClosed,'Voltmeter')-(1.5-.6*1.5/8.6))<.002);
run('simT=2');
const reopened=run('renderP6Scene()');
assert.equal(run('running'),false,'P6 opens automatically between readings');
assert.match(reopened,/last I 0.174 A · V 1.395 V/);
run('resetExperiment()');
assert.doesNotMatch(run('renderP6Scene()'),/LAST PAIR SAVED/,'Reset clears captured readings');
console.log('Practicals 4–6 run, detector and graph regressions passed.');
